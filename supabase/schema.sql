-- Coach Glycemie - schema cloud prive pour Supabase
-- Ce fichier peut etre rejoue sans supprimer les donnees existantes.

create table if not exists public.meals (
    id bigint generated by default as identity (start with 1000000) primary key,
    user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
    created_at timestamptz not null,
    description text not null,
    score integer not null check (score between 0 and 10),
    color text not null check (color in ('vert', 'orange', 'rouge')),
    comment text not null,
    model_name text not null,
    market_country text not null default 'Argentine',
    product_matches_json jsonb not null default '[]'::jsonb,
    meal_occurred_at timestamptz,
    meal_type text not null default 'Autre',
    meal_time text not null default '',
    meal_type_source text not null default '',
    eating_window_start text not null default '10:30',
    eating_window_hours integer not null default 10,
    inside_eating_window boolean,
    carbs_g double precision,
    protein_g double precision,
    fat_g double precision,
    macro_confidence text not null default ''
);

create table if not exists public.weights (
    id bigint generated by default as identity (start with 1000000) primary key,
    user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
    measured_on date not null,
    weight_kg double precision not null check (weight_kg > 0),
    note text not null default ''
);

create table if not exists public.symptom_events (
    id bigint generated by default as identity (start with 1000000) primary key,
    user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
    occurred_at timestamptz not null,
    kind text not null check (kind in ('faim', 'douleur')),
    pain_type text not null default '',
    intensity integer not null check (intensity between 1 and 10),
    note text not null default '',
    meal_id bigint references public.meals(id) on delete set null,
    delay_minutes integer,
    created_at timestamptz not null,
    reported_trigger text not null default '',
    source_text text not null default '',
    extraction_confidence text not null default 'manuelle'
);

create table if not exists public.bowel_events (
    id bigint generated by default as identity (start with 1000000) primary key,
    user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
    occurred_at timestamptz not null,
    bristol_type integer not null check (bristol_type between 1 and 7),
    description text not null default '',
    source_text text not null default '',
    extraction_confidence text not null default 'manuelle',
    created_at timestamptz not null
);

create table if not exists public.activity_events (
    id bigint generated by default as identity (start with 1000000) primary key,
    user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
    occurred_on date not null,
    activity_type text not null check (activity_type in ('Natation', 'Marche', 'Velo', 'Vélo')),
    intensity text not null default 'Modérée',
    duration_minutes double precision not null default 0,
    steps integer not null default 0,
    distance_km double precision not null default 0,
    calories_kcal double precision not null check (calories_kcal >= 0),
    estimation_method text not null default '',
    note text not null default '',
    created_at timestamptz not null
);

create table if not exists public.favorite_foods (
    id bigint generated by default as identity (start with 1000000) primary key,
    user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
    name text not null,
    brand text not null default '',
    aliases text not null default '',
    serving_size_g double precision not null default 0,
    calories_100g double precision not null default 0,
    carbs_100g double precision not null default 0,
    protein_100g double precision not null default 0,
    fat_100g double precision not null default 0,
    fiber_100g double precision not null default 0,
    notes text not null default '',
    country text not null default 'Argentine',
    data_source text not null default 'saisie_manuelle',
    barcode text not null default '',
    source_url text not null default '',
    updated_at timestamptz not null
);

create table if not exists public.profile (
    user_id uuid primary key default auth.uid() references auth.users(id) on delete cascade,
    display_name text not null default '',
    objective text not null default 'Stabiliser ma glycémie',
    country text not null default 'Argentine',
    eating_window_start text not null default '10:30',
    eating_window_hours integer not null default 10,
    height_cm double precision not null default 170,
    age_years integer not null default 56,
    sex text not null default 'Homme',
    activity_level text not null default 'Modérée',
    target_weight_kg double precision not null default 76,
    auto_macro_targets boolean not null default true,
    carbs_goal_g double precision not null default 150,
    protein_goal_g double precision not null default 100,
    fat_goal_g double precision not null default 70,
    calorie_goal_kcal double precision not null default 2000,
    meals_per_day integer not null default 2,
    updated_at timestamptz not null
);

create index if not exists idx_meals_user_occurred
    on public.meals(user_id, meal_occurred_at desc, created_at desc);
create index if not exists idx_weights_user_measured
    on public.weights(user_id, measured_on asc);
create index if not exists idx_symptoms_user_occurred
    on public.symptom_events(user_id, occurred_at desc);
create index if not exists idx_bowel_user_occurred
    on public.bowel_events(user_id, occurred_at desc);
create index if not exists idx_activity_user_occurred
    on public.activity_events(user_id, occurred_on desc);
create unique index if not exists idx_foods_user_name_brand
    on public.favorite_foods(user_id, lower(name), lower(brand));

alter table public.meals enable row level security;
alter table public.weights enable row level security;
alter table public.symptom_events enable row level security;
alter table public.bowel_events enable row level security;
alter table public.activity_events enable row level security;
alter table public.favorite_foods enable row level security;
alter table public.profile enable row level security;

revoke all on public.meals from anon;
revoke all on public.weights from anon;
revoke all on public.symptom_events from anon;
revoke all on public.bowel_events from anon;
revoke all on public.activity_events from anon;
revoke all on public.favorite_foods from anon;
revoke all on public.profile from anon;

grant select, insert, update, delete on public.meals to authenticated;
grant select, insert, update, delete on public.weights to authenticated;
grant select, insert, update, delete on public.symptom_events to authenticated;
grant select, insert, update, delete on public.bowel_events to authenticated;
grant select, insert, update, delete on public.activity_events to authenticated;
grant select, insert, update, delete on public.favorite_foods to authenticated;
grant select, insert, update, delete on public.profile to authenticated;
grant usage, select on all sequences in schema public to authenticated;

do $$
declare
    table_name text;
begin
    foreach table_name in array array[
        'meals', 'weights', 'symptom_events', 'bowel_events',
        'activity_events', 'favorite_foods', 'profile'
    ]
    loop
        execute format('drop policy if exists "owner_all" on public.%I', table_name);
        execute format(
            'create policy "owner_all" on public.%I for all to authenticated '
            'using ((select auth.uid()) = user_id) '
            'with check ((select auth.uid()) = user_id)',
            table_name
        );
    end loop;
end
$$;

